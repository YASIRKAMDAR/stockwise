    fun greeting(name: String): String {
        val h = java.util.Calendar.getInstance().get(java.util.Calendar.HOUR_OF_DAY)
        val g = if (h < 12) s("Good morning", "सुप्रभात", "સુપ્રભાત") else if (h < 17) s("Good afternoon", "नमस्ते", "નમસ્તે") else s("Good evening", "शुभ संध्या", "શુભ સાંજ")
        return "$g, $name"
    }
